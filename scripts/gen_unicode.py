#!/usr/bin/env python3
"""Generate src/Regex/UnicodeData.lean from Python's unicodedata.

Each Unicode general category becomes one string of inclusive ranges,
"0041-005A 0061-007A ...", which Regex.Unicode parses into a CharSet.
The tables are data, not code: regenerate them for a newer Unicode
version by running this script with a newer Python.

    python3 scripts/gen_unicode.py > src/Regex/UnicodeData.lean
"""

import sys
import unicodedata

# Major classes and the subcategories people actually write.
CATEGORIES = [
    "L", "Lu", "Ll", "Lt", "Lm", "Lo",
    "M", "Mn",
    "N", "Nd", "Nl", "No",
    "P", "S", "Z", "Zs",
]


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:  # surrogates are not characters
            hit = False
        else:
            hit = pred(unicodedata.category(chr(cp)))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    w = sys.stdout.write
    w("/-!\n")
    w("Unicode general-category tables, as data.\n\n")
    w("GENERATED by `scripts/gen_unicode.py` from Python's `unicodedata`\n")
    w(f"(Unicode {unicodedata.unidata_version}). Do not edit by hand.\n\n")
    w("Each table is a string of inclusive hex ranges, `lo-hi lo-hi ...`.\n")
    w("-/\n\n")
    w("namespace UnicodeData\n\n")
    # The output is generated: keep lean-fmt's hands off it.
    w("-- lean-fmt: format-ignore-next\n")
    w(f'/-- The Unicode version these tables were generated from. -/\n')
    w(f'def version : String := "{unicodedata.unidata_version}"\n\n')
    w("-- lean-fmt: format-ignore-next\n")
    w("/-- `(name, ranges)` for every supported general category. -/\n")
    w("def tables : List (String × String) :=\n  [")
    first = True
    for name in CATEGORIES:
        if len(name) == 1:
            rs = ranges(lambda c, n=name: c.startswith(n))
        else:
            rs = ranges(lambda c, n=name: c == n)
        body = " ".join(f"{lo:04X}-{hi:04X}" for lo, hi in rs)
        w(("" if first else ",\n   ") + f'("{name}", "{body}")')
        first = False
    w("]\n\nend UnicodeData\n")


if __name__ == "__main__":
    main()
